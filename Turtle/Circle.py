import turtle          
screen = turtle.Screen()
screen.bgcolor("black")
t = turtle.Turtle()
t.width(3)
t.color("blue")
t.penup()
t.goto(100, 100) 
t.pendown()
t.circle(100)
t.penup()
t.goto(100, -100) 
t.pendown()
t.circle(100)
t.penup()
t.goto(-100, -100) 
t.pendown()
t.circle(100)
t.penup()
t.goto(-100, 100) 
t.pendown()
t.circle(100)
t.penup()
t.goto(300, 100) 
t.pendown()
t.circle(100)
t.penup()
t.goto(300, -100) 
t.pendown()
t.circle(100)
turtle.done()